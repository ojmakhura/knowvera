package bw.co.knowvera.individual;

import java.util.List;

import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.domain.Sort;
import org.springframework.data.jpa.domain.Specification;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Transactional;

import bw.co.knowvera.ListProjection;
import bw.co.knowvera.kyc.KycComplianceStatus;
import jakarta.persistence.EntityManager;
import jakarta.persistence.Tuple;
import jakarta.persistence.criteria.CriteriaBuilder;
import jakarta.persistence.criteria.Root;
import jakarta.persistence.criteria.Selection;

/**
 * {@link IndividualListDTO}s read with a projection (see {@link ListProjection}). Hand-written:
 * {@code IndividualRepository} is generated by AndroMDA.
 */
@Component
@Transactional(readOnly = true)
public class IndividualListQueries extends ListProjection<Individual, IndividualListDTO> {

    public IndividualListQueries(EntityManager entityManager) {
        super(entityManager, Individual.class);
    }

    public List<IndividualListDTO> search(Specification<Individual> spec, Sort sort) {
        return list(spec, sort);
    }

    public Page<IndividualListDTO> search(Specification<Individual> spec, Pageable pageable) {
        return page(spec, pageable);
    }

    @Override
    protected List<Selection<?>> columns(Root<Individual> root, CriteriaBuilder cb) {
        return List.of(
                root.get("id").alias("id"),
                root.get("firstName").alias("firstName"),
                root.get("middleName").alias("middleName"),
                root.get("surname").alias("surname"),
                root.get("identityNo").alias("identityNo"),
                root.get("identityType").alias("identityType"),
                root.get("emailAddress").alias("emailAddress"),
                root.get("kycStatus").alias("kycStatus"),
                root.get("sex").alias("sex"),
                root.get("pepStatus").alias("pepStatus"),
                root.get("userCreated").alias("userCreated"),
                root.get("physicalAddress").alias("physicalAddress"),
                root.get("postalAddress").alias("postalAddress"));
    }

    @Override
    protected IndividualListDTO toDto(Tuple row) {
        return new IndividualListDTO(
                idOf(row, "id"),
                fullName(row.get("firstName", String.class), row.get("middleName", String.class),
                        row.get("surname", String.class)),
                row.get("identityNo", String.class),
                row.get("identityType", IndividualIdentityType.class),
                row.get("emailAddress", String.class),
                row.get("kycStatus", KycComplianceStatus.class),
                row.get("sex", Sex.class),
                row.get("pepStatus", PepStatus.class),
                row.get("userCreated", Boolean.class),
                row.get("physicalAddress", String.class),
                row.get("postalAddress", String.class));
    }
}
