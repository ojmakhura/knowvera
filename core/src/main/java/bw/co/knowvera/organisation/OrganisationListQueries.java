package bw.co.knowvera.organisation;

import java.util.List;

import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.domain.Sort;
import org.springframework.data.jpa.domain.Specification;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Transactional;

import bw.co.knowvera.GeneralStatus;
import bw.co.knowvera.ListProjection;
import bw.co.knowvera.kyc.KycComplianceStatus;
import jakarta.persistence.EntityManager;
import jakarta.persistence.Tuple;
import jakarta.persistence.criteria.CriteriaBuilder;
import jakarta.persistence.criteria.Root;
import jakarta.persistence.criteria.Selection;

/**
 * {@link OrganisationListDTO}s read with a projection (see {@link ListProjection}). Hand-written:
 * {@code OrganisationRepository} is generated by AndroMDA.
 */
@Component
@Transactional(readOnly = true)
public class OrganisationListQueries extends ListProjection<Organisation, OrganisationListDTO> {

    public OrganisationListQueries(EntityManager entityManager) {
        super(entityManager, Organisation.class);
    }

    public List<OrganisationListDTO> search(Specification<Organisation> spec, Sort sort) {
        return list(spec, sort);
    }

    public Page<OrganisationListDTO> search(Specification<Organisation> spec, Pageable pageable) {
        return page(spec, pageable);
    }

    @Override
    protected List<Selection<?>> columns(Root<Organisation> root, CriteriaBuilder cb) {
        return List.of(
                root.get("id").alias("id"),
                root.get("code").alias("code"),
                root.get("name").alias("name"),
                root.get("registrationNo").alias("registrationNo"),
                root.get("status").alias("status"),
                root.get("contactEmailAddress").alias("contactEmailAddress"),
                root.get("kycStatus").alias("kycStatus"),
                root.get("isClient").alias("isClient"),
                root.get("keycloakId").alias("keycloakId"),
                root.get("postalAddress").alias("postalAddress"),
                root.get("physicalAddress").alias("physicalAddress"));
    }

    @Override
    protected OrganisationListDTO toDto(Tuple row) {
        return new OrganisationListDTO(
                idOf(row, "id"),
                row.get("code", String.class),
                row.get("name", String.class),
                row.get("registrationNo", String.class),
                row.get("status", GeneralStatus.class),
                row.get("contactEmailAddress", String.class),
                row.get("kycStatus", KycComplianceStatus.class),
                row.get("isClient", Boolean.class),
                row.get("keycloakId", String.class),
                row.get("postalAddress", String.class),
                row.get("physicalAddress", String.class));
    }
}
